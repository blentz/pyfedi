class TestThePronounsShownBesideAName:
    """A self-set profile field, rendered beside the username everywhere it appears. That
    makes it attacker-controlled display text, which is what the length limit and the HTML
    handling are for.
    """

    @pytest.fixture
    def real_cache(self, app, monkeypatch):
        from cachelib import SimpleCache

        monkeypatch.setitem(app.extensions['cache'], cache, SimpleCache())
        cache.delete_memoized(user_pronouns)
        return cache

    def _field(self, env, user, label, text):
        db.session.add(UserExtraField(user_id=user.id, label=label, text=text))
        db.session.commit()
        cache.delete_memoized(user_pronouns)

    @pytest.mark.parametrize('label', ['Pronouns', 'pronouns', 'PRONOUNS'])
    def test_the_field_is_matched_case_insensitively(self, env, real_cache, label):
        """`func.lower(label) == 'pronouns'`. The label is typed by the account holder, so
        the capitalisation is theirs."""
        user = make_user(env.baseline.instance_local, f'person{label}', local=True)
        db.session.commit()
        self._field(env, user, label, 'they/them')

        assert user_pronouns()[user.id] == 'they/them'

    def test_a_long_value_is_not_shown_at_all(self, env, real_cache):
        """`len(text) <= 22`. The value goes beside a username in every listing, so an
        overlong one is dropped rather than truncated -- a cut-off pronoun would be worse
        than none."""
        user = make_user(env.baseline.instance_local, 'verbose', local=True)
        db.session.commit()
        self._field(env, user, 'Pronouns', 'x' * 23)

        assert user.id not in user_pronouns()

    def test_a_value_of_exactly_the_limit_is_shown(self, env, real_cache):
        user = make_user(env.baseline.instance_local, 'exact', local=True)
        db.session.commit()
        self._field(env, user, 'Pronouns', 'x' * 22)

        assert user_pronouns()[user.id] == 'x' * 22

    def test_markup_is_reduced_to_text(self, env, real_cache):
        """`if '<' in text and '>' in text: html_to_text(...)`. The field is rendered beside
        a name, and this is the line that stops somebody's 'pronouns' being markup."""
        user = make_user(env.baseline.instance_local, 'markupper', local=True)
        db.session.commit()
        self._field(env, user, 'Pronouns', '<b>they</b>')

        assert user_pronouns()[user.id] == 'they'

    def test_a_missing_account_has_no_pronouns(self, env, real_cache):
        """The return is a `defaultdict(str)`, so a template asking about any account gets
        an empty string rather than a KeyError -- which is what lets the caller render it
        unconditionally."""
        assert user_pronouns()[999999] == ''
