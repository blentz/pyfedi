class TestReadingAPagesMetaTags:
    """`parse_page` fetches a URL and reads its OpenGraph tags; its tail fills in from
    ordinary HTML what the page did not say in `og:`. These values are rendered beside a link
    post, so the fallbacks decide what a reader sees for a page with no OpenGraph at all.
    """

    def _parse(self, html):
        """`parse_page` fetches through `get_request`, which is memoized and does its own
        SSRF checking -- so the fetch is replaced at that level rather than at the http
        client."""
        response = SimpleNamespace(
            status_code=200,
            headers={'Content-Type': 'text/html'},
            text=html,
            content=html.encode(),
            close=lambda: None)
        with patch('app.utils.get_request', return_value=response):
            return parse_page('https://news.example/story')

    def test_a_pages_opengraph_tags_are_read(self):
        tags = self._parse('<html><head>'
                           '<meta property="og:title" content="A Story">'
                           '<meta property="og:image" content="https://x/y.png">'
                           '</head><body></body></html>')

        assert tags['og:title'] == 'A Story'
        assert tags['og:image'] == 'https://x/y.png'

    def test_a_plain_description_meta_is_used(self):
        """`<meta name="description">` is what most pages have and OpenGraph is what few of
        them have, so this fallback is the common case rather than the edge one."""
        tags = self._parse('<html><head>'
                           '<meta property="og:title" content="A Story">'
                           '<meta name="description" content="what it is about">'
                           '</head></html>')

        assert tags['description'] == 'what it is about'
        assert tags['og_description'] == 'what it is about'

    def test_an_opengraph_description_is_copied_to_the_plain_key(self):
        """The other direction: a page with only `og:description` gets `description` too, so
        a caller reading either key finds it."""
        tags = self._parse('<html><head>'
                           '<meta property="og:title" content="A Story">'
                           '<meta property="og:description" content="from opengraph">'
                           '</head></html>')

        assert tags['description'] == 'from opengraph'

    def test_a_page_with_both_descriptions_keeps_them_apart(self):
        """`if "og:description" not in found_tags`. A page that gives both gets
        `description` from the plain meta and `og:description` under its own key -- and NOT
        `og_description`, which exists only as a stand-in for a page that has no OpenGraph
        description at all. Without that test the stand-in would shadow the real one.
        """
        tags = self._parse('<html><head>'
                           '<meta property="og:title" content="A Story">'
                           '<meta property="og:description" content="from opengraph">'
                           '<meta name="description" content="from the plain meta">'
                           '</head></html>')

        assert tags['og:description'] == 'from opengraph'
        assert tags['description'] == 'from the plain meta'
        assert 'og_description' not in tags

    def test_the_title_element_stands_in_for_a_missing_og_title(self):
        """`if len(found_tags) == 0 or 'og:title' not in found_tags`. Without this a page
        with no OpenGraph shows a link post with no title at all."""
        tags = self._parse('<html><head><title>The Real Title</title></head></html>')

        assert tags['og:title'] == 'The Real Title'

    def test_a_page_with_an_og_title_keeps_it(self):
        """The `<title>` is usually the site name appended to the headline, so it must not
        override a page that said what it wanted."""
        tags = self._parse('<html><head>'
                           '<meta property="og:title" content="The Headline">'
                           '<title>The Headline | Some Site</title>'
                           '</head></html>')

        assert tags['og:title'] == 'The Headline'

    def test_a_page_with_nothing_readable_gives_nothing(self):
        """`if title:` -- a page with neither OpenGraph nor a `<title>`. The answer is an
        empty dict, which every caller tests for before using it."""
        assert self._parse('<html><body>just words</body></html>') == {}


