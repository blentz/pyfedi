class _FakeReader:
    """Stands in for `c2pa.Reader`. The real one parses a signed manifest out of image bytes;
    what this module does with the parsed dict is the part under test.
    """

    def __init__(self, manifest):
        self._manifest = manifest

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False

    def get_active_manifest(self):
        return self._manifest


class _FakeContext:
    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False


def _c2pa(manifest, reader_error=None):
    """Patch the `c2pa` module `inspect_image_c2pa` imports inside itself."""
    module = SimpleNamespace(
        Context=lambda: _FakeContext(),
        Reader=(lambda *args, **kwargs: (_ for _ in ()).throw(reader_error))
        if reader_error else (lambda *args, **kwargs: _FakeReader(manifest)))
    return patch.dict('sys.modules', {'c2pa': module})


def actions_manifest(source, action='c2pa.created', generator='Some Camera 1.0'):
    return {'claim_generator': generator,
            'assertions': [{'label': 'c2pa.actions',
                            'data': {'actions': [{'action': action,
                                                  'digitalSourceType': source}]}}]}


class TestReadingAnImagesProvenance:

    def test_an_image_with_no_manifest_says_so(self):
        """The default dict, returned whenever the reader raises -- which is what an
        ordinary photograph with no C2PA data does. Every field is falsy, so a caller that
        checks `['c2pa']['ai_generated']` sees False rather than a KeyError."""
        with _c2pa(None, reader_error=ValueError('no manifest')):
            answer = inspect_image_c2pa(b'not an image', 'image/png')

        assert answer == {'c2pa': {'present': False, 'ai_generated': False,
                                   'creator': None, 'software': None}}

    def test_a_readable_manifest_is_present_even_with_nothing_in_it(self):
        """`present` is set before the manifest is read, so an image carrying an EMPTY
        manifest still reports provenance -- which is the honest answer: something signed
        it."""
        with _c2pa(None):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['present'] is True
        assert answer['c2pa']['creator'] is None

    def test_the_claim_generator_becomes_the_creator(self):
        with _c2pa(actions_manifest('digitalCapture', generator='Fancy Camera 2.0')):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['creator'] == 'Fancy Camera 2.0'

    @pytest.mark.parametrize('action', ['c2pa.created', 'c2pa.placed'])
    def test_a_trained_model_source_marks_the_image_ai_generated(self, action):
        """The answer that matters. `trainedAlgorithmicMedia` is the IPTC term for
        model-generated media, and it is accepted under either action -- `created` for an
        image a model made and `placed` for one composited into another."""
        source = 'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia'
        with _c2pa(actions_manifest(source, action=action)):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['ai_generated'] is True

    def test_a_camera_capture_is_not_ai_generated(self):
        """The control, and the expensive direction: labelling a photograph as AI would put
        a warning on somebody's own picture."""
        source = 'http://cv.iptc.org/newscodes/digitalsourcetype/digitalCapture'
        with _c2pa(actions_manifest(source)):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['ai_generated'] is False
        assert answer['c2pa']['present'] is True

    def test_an_action_this_code_does_not_read_is_ignored(self):
        """`if action_name in [...]`. An `c2pa.edited` action naming a model source says the
        image was EDITED with a model, not generated by one -- a different claim, and not the
        one this flag makes."""
        source = 'trainedAlgorithmicMedia'
        with _c2pa(actions_manifest(source, action='c2pa.edited')):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['ai_generated'] is False

    def test_an_assertion_that_is_not_about_actions_is_ignored(self):
        """`label.startswith('c2pa.actions')`. A manifest carries many assertion types, and
        reading a training-and-data-mining assertion as an action would be a different
        claim again."""
        manifest = {'claim_generator': 'Some Tool',
                    'assertions': [{'label': 'c2pa.training-mining',
                                    'data': {'actions': [
                                        {'action': 'c2pa.created',
                                         'digitalSourceType': 'trainedAlgorithmicMedia'}]}}]}
        with _c2pa(manifest):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['ai_generated'] is False

    def test_a_manifest_with_no_assertions_at_all_is_harmless(self):
        """`manifest.get('assertions', [])` -- the key is optional, and iterating None
        would raise inside the `try`, which would silently become "no provenance" and lose
        the `present` flag the reader had already established."""
        with _c2pa({'claim_generator': 'Some Tool'}):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['present'] is True
        assert answer['c2pa']['creator'] == 'Some Tool'
        assert answer['c2pa']['ai_generated'] is False

    def test_an_action_with_no_source_is_not_ai_generated(self):
        """`action.get('digitalSourceType', '')`. The key is optional, and
        `'x' in None` is a `TypeError`."""
        manifest = {'claim_generator': 'Some Tool',
                    'assertions': [{'label': 'c2pa.actions',
                                    'data': {'actions': [{'action': 'c2pa.created'}]}}]}
        with _c2pa(manifest):
            answer = inspect_image_c2pa(b'bytes', 'image/jpeg')

        assert answer['c2pa']['ai_generated'] is False


