"""Round 247: content provenance, the OpenGraph fallbacks, and pronouns.

Three clusters in `app/utils.py`.

`inspect_image_c2pa` reads an uploaded image's C2PA manifest to answer two questions: is
there provenance at all, and does it say the image was generated by a model. The answer sets
`Post.ai_generated`, which viewers filter on -- so a manifest read wrongly either labels
somebody's photograph as AI or lets generated media through a filter somebody asked for. The
whole body is wrapped in `except Exception: pass`, because the input is an arbitrary upload.

`parse_page`'s tail fills in what a page did not give as OpenGraph: a `<meta name=description>`
becomes the description, and a `<title>` becomes `og:title`. These are the values rendered
beside a link post.

`user_pronouns` renders a self-set profile field beside a username, with a length limit and an
HTML escape hatch.
"""
